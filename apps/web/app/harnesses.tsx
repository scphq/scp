export function HarnessIcon({ h, size = 14 }: { h: Harness; size?: number }) {
  const v = 24 / (HARNESS[h].scale ?? 1);
  const o = 12 - v / 2;
  return (
    <svg
      className={`h-icon h-${h}`}
      width={size}
      height={size}
      viewBox={`${o} ${o} ${v} ${v}`}
      overflow="visible"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      {HARNESS[h].parts.map((p) => (
        <path key={p.d} d={p.d} fillOpacity={p.alpha} fillRule={p.evenodd ? "evenodd" : undefined} />
      ))}
    </svg>
  );
}

const paths = new Map<string, Path2D>();

/** Draw a harness mark centred on (x, y), `size` px square, in `color`. */
export function drawHarness(ctx: CanvasRenderingContext2D, h: Harness, x: number, y: number, size: number, color: string) {
  ctx.save();
  const k = (size * (HARNESS[h].scale ?? 1)) / 24;
  ctx.translate(Math.round(x), Math.round(y));
  ctx.scale(k, k);
  ctx.translate(-12, -12);
  ctx.fillStyle = color;
  const base = ctx.globalAlpha;
  for (const p of HARNESS[h].parts) {
    const path = paths.get(p.d) ?? new Path2D(p.d);
    paths.set(p.d, path);
    ctx.globalAlpha = base * (p.alpha ?? 1);
    ctx.fill(path, p.evenodd ? "evenodd" : "nonzero");
  }
  ctx.restore();
}
